#include "libft.h"

char	*ft_strdup(const char *str)
{
	size_t	len_str;
	char	*dest;
	int		i;

	len_str = ft_strlen(str);
	dest = (char *)malloc(sizeof(char) * (len_str + 1));
	if (!dest)
		return (NULL);
	i = 0;
	while (str[i])
	{
		dest[i] = str[i];
		i++;
	}
	dest[i] = '\0';
	return (dest);
}
